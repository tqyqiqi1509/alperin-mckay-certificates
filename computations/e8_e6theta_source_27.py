"""Uniform E6-source torus inside the Euclidean E8 lattice.

No field orders are sampled.  The E6 roots are those orthogonal to the
A2 root lattice on the final three coordinates.  The complete relative
normalizer is generated by the complementary A2 reflections and -I(E8).
"""
from itertools import combinations, product
from collections import deque, Counter
from pathlib import Path
import json
import sympy as S

roots=set()
for i,j in combinations(range(8),2):
    for a,b in product((-2,2),repeat=2):
        r=[0]*8;r[i]=a;r[j]=b;roots.add(tuple(r))
for signs in product((-1,1),repeat=8):
    if sum(t<0 for t in signs)%2==0:roots.add(signs)
assert len(roots)==240
Y=S.zeros(8,2)
Y[5,0]=1;Y[6,0]=-1;Y[6,1]=1;Y[7,1]=-1
Q=Y.T*Y
assert Q==S.Matrix([[2,-1],[-1,2]]) and Q.det()==3
restr=[]
for r in sorted(roots):
    a=S.Matrix(1,8,r)*Y/2
    assert all(v.q==1 for v in a)
    restr.append(tuple(map(int,a)))
assert sum(not any(r) for r in restr)==72
assert sum(all(v%5==0 for v in r) for r in restr)==72

def key(m):return tuple(map(int,m))
def matrix(k):return S.Matrix(2,2,k)
gens=[];lifts=[]
for i in range(2):
    g=S.eye(2)
    for j in range(2):g[i,j]-=Q[i,j]
    gens.append(key(g))
    a=Y[:,i];lifts.append(S.eye(8)-a*a.T)
gens.append(key(-S.eye(2)));lifts.append(-S.eye(8))
for lift in lifts:
    assert {tuple(lift*S.Matrix(r)) for r in roots}==roots
seen={key(S.eye(2))};todo=deque(seen)
while todo:
    a=todo.popleft()
    for g in gens:
        b=key(matrix(a)*matrix(g))
        if b not in seen:seen.add(b);todo.append(b)
assert len(seen)==12
rows=[]
for z in product(range(2),repeat=2):
    if not any(z):continue
    stable=[w for w in seen if tuple(int(v)%2 for v in matrix(w)*S.Matrix(z))==z]
    nr=sum(sum(a*b for a,b in zip(r,z))%2==0 for r in restr)
    assert nr==128 and len(stable)==4
    assert all(matrix(w)**2==S.eye(2) for w in stable)
    assert key(-S.eye(2)) in stable
    rows.append({'z':z,'centralizing_roots':nr,'relative_stabilizer':4,
                 'all_stabilizer_elements_have_order_at_most_two':True})
data={'description':'E8 E6 source: actual central A2 lattice and all involution parameters',
      'central_lattice_basis':[[int(v) for v in row] for row in Y.tolist()],
      'gram_matrix':[[int(v) for v in row] for row in Q.tolist()],
      'source_root_count':72,'roots_trivial_on_central_five_torsion':72,
      'relative_normalizer_order':len(seen),'relative_group':'W(G2)',
      'opposition_lift':'-I_8, an actual E8 Weyl element',
      'two_torsion_rows':rows,
      'root_restriction_multiplicities':{str(k):v for k,v in Counter(restr).items()},
      'all_assertions_passed':True}
out=Path(__file__).with_suffix('.json')
out.write_text(json.dumps(data,indent=2)+'\n')
print(json.dumps({k:v for k,v in data.items() if k!='root_restriction_multiplicities'},indent=2))
