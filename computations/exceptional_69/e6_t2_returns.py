"""Uniform E8/E6T2 rational returns from the Cartan lattice alone.

The finite groups are not sampled at small q.  Character assertions are
proved in construction 69, not inferred from this root calculation.
"""
from pathlib import Path
import json
import sympy as sp
from levi_lattices import cartan, roots_from_reflections, integer_nullbasis, longest

OUT = Path(__file__).resolve().parent
C = cartan(8)
roots = roots_from_reflections(C)
I = list(range(6))
B = integer_nullbasis(C[I, :])
assert B[:, 0] == sp.Matrix([2, 3, 4, 6, 5, 4, 3, 0])
assert B[:, 1] == sp.eye(8)[:, 7]
beta1 = B[:, 1]
beta2 = B[:, 0] + B[:, 1]
orthogonal = [sp.Matrix(v) for v in roots if C[I, :] * sp.Matrix(v) == sp.zeros(6, 1)]
expected = [beta1, -beta1, beta2, -beta2, beta1 + beta2, -beta1 - beta2]
assert {tuple(v) for v in orthogonal} == {tuple(v) for v in expected}

def reflection(beta):
    M = sp.eye(8) - beta * beta.T * C
    assert M * M == sp.eye(8)
    assert M[:, I] == sp.eye(8)[:, I]
    return M

def centre_matrix(M):
    X = B.gauss_jordan_solve(M * B)[0]
    assert all(x.q == 1 for x in X)
    return X

s1 = centre_matrix(reflection(beta1))
s2 = centre_matrix(reflection(beta2))
wH, _ = longest(C, I)
r = -wH
assert centre_matrix(r) == -sp.eye(2)
assert r[:, 0] == sp.eye(8)[:, 5]
assert r[:, 2] == sp.eye(8)[:, 4]

def key(M):
    return tuple(M)

S3 = {key(sp.eye(2)): sp.eye(2)}
frontier = [sp.eye(2)]
while frontier:
    M = frontier.pop()
    for generator in [s1, s2]:
        N = M * generator
        if key(N) not in S3:
            S3[key(N)] = N
            frontier.append(N)
assert len(S3) == 6
D12 = {**S3, **{key(-M): -M for M in S3.values()}}
assert len(D12) == 12
classes = []
unseen = set(D12)
while unseen:
    k = min(unseen)
    M = D12[k]
    cl = {key(g * M * g.inv()) for g in D12.values()}
    classes.append(cl)
    unseen -= cl
assert len(classes) == 6

q = sp.Symbol("q", integer=True)
J = B[[6, 7], :]
assert J == sp.diag(3, 1)
representatives = [
    ("split", sp.eye(2), 1),
    ("opposition", -sp.eye(2), -1),
    ("A2_reflection", s1, 1),
    ("negative_A2_reflection", -s1, -1),
    ("A2_order3", s1 * s2, 1),
    ("negative_A2_order3", -s1 * s2, -1),
]
values = []
for name, U, epsilon in representatives:
    cl = {key(g * U * g.inv()) for g in D12.values()}
    assert cl in classes
    # The cubic multiplication kernel is generated by B[:,0]/3.
    assert int(U[1, 0]) % 3 == 0
    assert int(U[0, 0]) % 3 == epsilon % 3
    Uquot = J * U * J.inv()
    assert all(x.q == 1 for x in Uquot)
    order = next(n for n in range(1, 7) if U**n == sp.eye(2))
    values.append({
        "name": name,
        "centre_return": [[int(x) for x in row] for row in U.tolist()],
        "quotient_return": [[int(x) for x in row] for row in Uquot.tolist()],
        "derived_E6_sign": epsilon,
        "return_order": order,
        "class_size": len(cl),
        "fixed_torus_order": str(sp.factor((q * U - sp.eye(2)).det() * (1 if U.det() > 0 else -1))),
        "cubic_kernel_F_action": "epsilon*q mod 3",
        "Lang_cokernel_order": "gcd(3,q-epsilon)",
    })
assert len({frozenset(key(g * U * g.inv()) for g in D12.values()) for _, U, _ in representatives}) == 6
result = {
    "main_theorem_closed": False,
    "input": "Bourbaki E8 Cartan graph only",
    "centre_gram": [[int(x) for x in row] for row in (B.T * C * B).tolist()],
    "orthogonal_root_count": len(orthogonal),
    "relative_group_order": len(D12),
    "rational_return_classes": values,
}
(OUT / "e6_t2_returns.json").write_text(json.dumps(result, indent=2) + "\n")
for value in values:
    print(value["name"], "E6 sign", value["derived_E6_sign"],
          "order", value["return_order"], "torus", value["fixed_torus_order"],
          "matrix", value["centre_return"])
