I960=Permutation(list(range(960)))
def phase_lift(p):
    return Permutation([p(i)%240+240*((j+2*(p(i)//240))%4) for j in range(4) for i in range(240)])
def torus4(v):
    y=coeff_y(v);ph=[(dot(r,y)//4)%4 for r in ROOTS]
    return Permutation([i+240*((j+ph[i])%4) for j in range(4) for i in range(240)])
IOTA=Permutation([i+240*((-j)%4) for j in range(4) for i in range(240)])
def combos(ker,m):
    for c in product(range(m),repeat=len(ker)):
        yield [sum(c[j]*ker[j][i] for j in range(len(ker)))%m for i in range(8)]
def action_vector(w,y):
    co=Matrix([y])*BI
    return tuple(sum(int(co[j])*ROOTS[w(INDEX[SIMPLE[j]])][i] for j in range(8)) for i in range(8))
def zeta(v,row,q=1,opposite=False):
    y=coeff_y(v)
    w=signed_weyl(row['signed']) if 'signed' in row else regular_weyl(row['base'])
    wy=action_vector(w,y)
    if opposite:wy=neg(wy)
    diff=tuple(q*wy[i]-y[i] for i in range(8))
    if row['kind']=='D':a=Fraction(sum(diff[i] for i in [5,6,7]),8)
    else:a=Fraction(dot(diff,(-1,1,1,1,1,1,1,7)),32)
    a%=1
    assert a in [0,Fraction(1,2)],('not a two-line',row['name'],v,a)
    return int(2*a)

def extension_check(G,zlist,extra):
    """K generated by zlist and commuting extras; prescribed values in C4.
    Values are exponents of i. A line on K extends to G iff trivial on K∩G'.
    """
    derived=G.derived_subgroup()
    known={};bad=[]
    orders=[int(p.order()) for p,e in extra]
    for exponents in product(*[range(o) for o in orders]):
        p=G.identity;value=0
        for k,(g,e) in zip(exponents,extra):p=p*(g**k);value+=k*e
        for z,zv in zlist:
            x=z*p;val=(zv+value)%4;key=tuple(x.array_form)
            if key in known and known[key][1]!=val:bad.append(('inconsistent',val,known[key][1]))
            else:known[key]=(x,val)
    derivedbad=[v for x,v in known.values() if v and derived.contains(x)]
    return {'derived_order':int(derived.order()),'abelian_invariants':list(map(int,G.abelian_invariants())),'prescribed_subgroup_order':len(known),'assignment_consistent':not bad,'kills_derived_intersection':not derivedbad,'bad_values':derivedbad[:6]}

def buildphase(row):
    start=time.time();f=OUT/('e8_quartic19_'+row['name']+'.pickle');d=pickle.loads(f.read_bytes())
    E=PermutationGroup(list(d['E0'].args));n=d['n'];n0,_=longest(SIMPLE);l0,_=longest(row['base']);h=n0*l0**-1
    assert E.contains(h) and all(h*g==g*h for g in E.generators)
    if 'signed' not in row:n=h
    zall=[]
    for v in combos(d['ker2'],2):
        z=torus2(coeff_y(v))
        if z*n==n*z:
            zall.append((v,z,2*zeta(v,row)))
    out={'row':row['name'],'h_order':int(h.order()),'n_order':int(n.order()),'nh_order':int((n*h).order()),'rational_center2_order':len(zall),'line_mod8_covariant':all(zeta(v,row,1)==zeta(v,row,5)==zeta(v,row,3,True)==zeta(v,row,7,True) for v,z,val in zall)}
    if 'signed' not in row:
        out['regular_extension']=extension_check(E,[(z,val) for v,z,val in zall],[(n,0)])
        out['E0_order']=int(E.order());out['P_order']=int(E.order());out['Q_order']=int(E.order())
    else:
        np=phase_lift(n);hp=phase_lift(h)
        P4=PermutationGroup([phase_lift(g) for g in E.generators]+[torus4(v) for v in d['ker4']])
        out['P4_order']=int(P4.order());print(row['name'],'P4',P4.order(),flush=True)
        P=P4.centralizer(np);out['P_order']=int(P.order());print(row['name'],'P',P.order(),flush=True)
        Q=PermutationGroup(P.generators+[IOTA]);out['Q_order']=int(Q.order())
        assert Q.contains(hp)
        out['h_equals_iota_on_P']=all(hp**-1*g*hp==IOTA**-1*g*IOTA for g in P.generators)
        out['P_weyl_image']=int(PermutationGroup([shadow(g) for g in P.generators]).order())
        out['signed_centralizer_image']=int(PermutationGroup([shadow(g) for g in E.centralizer(n).generators]).order())
        desiredn=2 if row['name']=='A7A1_external_A1' else 0
        out['quartic_extension']=extension_check(Q,[(phase_lift(z),val) for v,z,val in zall],[(np,desiredn),(hp,2)])
        cache={'row':row,'Pgens':[g.array_form for g in P.generators],'Qgens':[g.array_form for g in Q.generators],'n':np.array_form,'h':hp.array_form,'zlist':[(v,phase_lift(z).array_form,val) for v,z,val in zall]}
        (OUT/('e8_quartic19_'+row['name']+'_phase.pickle')).write_bytes(pickle.dumps(cache))
    out['seconds']=time.time()-start
    (OUT/('e8_quartic19_'+row['name']+'_phase.json')).write_text(json.dumps(out,indent=2));print(json.dumps(out),flush=True)

